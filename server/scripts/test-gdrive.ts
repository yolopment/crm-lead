import fs from 'fs';
import path from 'path';
import { config } from '../src/config/index.js';
import {
  isGoogleDriveConfigured,
  getDriveClient,
  uploadToGoogleDrive,
  deleteFromGoogleDrive,
} from '../src/services/gdrive.service.js';

async function testGDriveConnection() {
  console.log('====================================================');
  console.log('🚀 CRM-LEAD: Google Drive Storage Connection Tester');
  console.log('====================================================');
  console.log(`• Storage Driver       : ${config.storageDriver}`);
  console.log(`• Target Folder ID     : ${config.gdriveFolderId || '(Not configured)'}`);
  console.log(`• Credentials File     : ${config.gdriveCredentialsPath || '(None)'}`);
  console.log(`• Credentials JSON     : ${config.gdriveServiceAccountJson ? '(Configured via JSON string)' : '(None)'}`);
  console.log(`• Service Account Email: ${config.gdriveClientEmail || '(Derived from credentials)'}`);
  console.log('----------------------------------------------------');

  if (!isGoogleDriveConfigured()) {
    console.log('ℹ️  Google Drive is not fully configured in your server/.env.');
    console.log('\nTo set up Google Drive storage:');
    console.log('1. Create a Google Cloud Project & Service Account.');
    console.log('2. Download the JSON key file (e.g. google-service-account.json).');
    console.log('3. In your Google Drive, create a folder (e.g. "CRM Call Recordings").');
    console.log('4. Click Share on that folder and add your Service Account email as "Editor".');
    console.log('5. Copy the Folder ID from the URL and update server/.env:');
    console.log('----------------------------------------------------');
    console.log('STORAGE_DRIVER=dual  # or "gdrive"');
    console.log('GOOGLE_APPLICATION_CREDENTIALS="./google-service-account.json"');
    console.log('GOOGLE_DRIVE_FOLDER_ID="your_google_drive_folder_id"');
    console.log('----------------------------------------------------');
    return;
  }

  const drive = getDriveClient();
  if (!drive) {
    console.error('❌ Failed to initialize Google Drive client. Please check your credentials JSON/path.');
    process.exit(1);
  }

  try {
    console.log('\n⏳ Step 1: Checking Google Drive target folder access...');
    const folder = await drive.files.get({
      fileId: config.gdriveFolderId,
      fields: 'id, name, mimeType',
    });
    console.log(`   ✅ Target Folder found: "${folder.data.name}" (ID: ${folder.data.id})`);

    console.log('\n⏳ Step 2: Uploading test recording file to Google Drive...');
    const tempTestPath = path.join(config.recordingsDir, `test-gdrive-${Date.now()}.txt`);
    fs.writeFileSync(tempTestPath, 'CRM-LEAD Google Drive connection test passed successfully!');

    const uploadResult = await uploadToGoogleDrive(
      tempTestPath,
      `CRM-Test-${Date.now()}.txt`,
      'text/plain',
      'Temporary test file generated by CRM-LEAD connection tester'
    );

    if (fs.existsSync(tempTestPath)) {
      fs.unlinkSync(tempTestPath);
    }

    if (!uploadResult || !uploadResult.fileId) {
      throw new Error('Upload failed. No file ID returned.');
    }

    console.log(`   ✅ Successfully uploaded test file to Google Drive!`);
    console.log(`   🔗 Google Drive Link: ${uploadResult.webViewLink}`);

    console.log('\n⏳ Step 3: Cleaning up test file from Google Drive...');
    await deleteFromGoogleDrive(uploadResult.fileId);
    console.log(`   ✅ Test file successfully deleted from Google Drive.`);

    console.log('\n====================================================');
    console.log('🎉 SUCCESS: Google Drive is 100% CONNECTED & WORKING!');
    if (config.storageDriver === 'dual' || config.storageDriver === 'both') {
      console.log('🌟 DUAL MODE ACTIVE: Recordings will stream via Cloudflare R2');
      console.log('   and automatically back up to your Google Drive folder!');
    } else {
      console.log('Recordings will be saved directly to your Google Drive.');
    }
    console.log('====================================================');
  } catch (err: any) {
    console.error('\n❌ Google Drive Connection Failed!');
    console.error(`Details: ${err.message}`);
    if (err.code === 404) {
      console.error('👉 The folder ID was not found or your Service Account does not have access.');
      console.error('👉 Make sure you shared the folder with your Service Account email as Editor!');
    }
    process.exit(1);
  }
}

testGDriveConnection();
